/**
 * findings.ts — the closed list of things the engine can SAY (engine spec
 * §6.10). A fixed kind, a fixed rank, numbers already formatted, and no
 * text generated by a model.
 *
 * The rule the copy templates are written to: no sentence asserts a CAUSE.
 * "Activation is below its target and onboarding completion isn't
 * tracked" is a finding; "it's the onboarding" is an opinion.
 *
 * An unknown becomes a finding only once someone has looked for it and
 * couldn't find it (`missing`). A number still to do or awaiting a reply is
 * collection in progress, not a fact about the company — it shows in the
 * coverage and the "to go and get" list, never here.
 *
 * `values` carries only formatted NUMBERS. The names the templates also need
 * — a metric's name (`{metric}`, `{input}`), a stage verb (`{verb}`), a
 * source's label (`{sourceA}`) — are copy, resolved by the consumer from
 * `finding.metrics` and the maps below, exactly like every other label.
 */

/** Which `findings.verb.*` a chain break uses — the column's own verb. */
export const CHAIN_VERB: Record<PelotonMetric, "activated" | "d30" | "paid"> = {
  "act.rate": "activated",
  "ret.d30": "d30",
  "rev.paid-conversion": "paid",
};

/**
 * Which `findings.verbMkt.*` a marketplace's chain break uses — the column's own verb (§22.8.5 j): the buyers'
 * first and second order, the sellers' first sale and, with subscriptions, their subscription.
 */
export const MKT_CHAIN_VERB = {
  "mkt.buy.first-order": "first",
  "mkt.buy.repeat": "repeat",
  "mkt.sell.first-sale": "firstSale",
  "mkt.sell.paid-conversion": "paid",
} as const;
export type MktChainColumn = keyof typeof MKT_CHAIN_VERB;

const RANK: Record<Finding["kind"], Finding["rank"]> = {
  "chain-break": 1,
  // C48: as grave as a missing link — without it, each new customer digs the hole deeper.
  "unit-econ-loss": 1,
  "no-definition": 2,
  "blind-spot": 2,
  "below-comparator": 2,
  "unit-econ-loss-maybe": 2,
  conflict: 3,
  "unit-econ-uncomputable": 3,
  "reconcile-gap": 3,
  "small-cohort": 4,
  "small-sample": 4,
  "hidden-knowledge": 4,
};

/** Order within a rank, so the list is stable across renders and screens. */
const KIND_ORDER = Object.keys(RANK) as Finding["kind"][];

function formatReading(value: MetricValue, id: MetricId, state: EngineState, ctx: EngineCalcContext, words: UnitWords): string {
  const shape = shapeOf(id);
  const v = readingValue(value, shape);
  return v === null ? "" : formatInterval(point(v), shape.unit, ctx, words, { currency: state.setup.currency });
}

/** "20 %" — the team's target, formatted in the metric's unit. */
export function formatComparator(comparator: Comparator, id: MetricId, state: EngineState, ctx: EngineCalcContext, words: UnitWords): string {
  const range: Interval = { lo: comparator.lo, hi: comparator.hi };
  return formatInterval(range, shapeOf(id).unit, ctx, words, { currency: state.setup.currency });
}

/**
 * The findings of the ticked motions, each tagged with its motion (§18.5.8),
 * then sorted: by rank, by kind, and within a kind in canonical order —
 * self-serve's before sales-assisted's, never by a value. The link makes no
 * finding: it is optional, and its absence says nothing about the company.
 * A marketplace's findings also say the side of their number (§22.5.8), the
 * demand's before the supply's within a kind.
 */
export function findings(state: EngineState, derived: Omit<EngineDerived, "findings">, ctx: EngineCalcContext, words: UnitWords): Finding[] {
  const snapshot = currentSnapshot(state);
  const out: Finding[] = [];
  // A marketplace's finding also says which side it is about (C70).
  const addFor =
    (motion: EngineMotion, side?: MktSide) =>
    (kind: Finding["kind"], metrics: Finding["metrics"], values: Record<string, string> = {}, count?: Interval) =>
      out.push({ kind, motion, ...(side ? { side } : {}), rank: RANK[kind], metrics, values, ...(count ? { count } : {}) });
  const missing = (id: MetricId) => statusOf(entryOf(snapshot, id)) === "missing";

  for (const m of derived.motions) {
    if (m.motion === "mkt") marketplaceFindings(state, m, derived, ctx, words, (side) => addFor("mkt", side), missing);
    else {
      const add = addFor(m.motion);
      if (m.motion === "plg") selfServeFindings(state, m, derived, ctx, words, add, missing);
      else salesAssistedFindings(state, m, ctx, words, add, missing);
    }
  }

  // The Tour's four bridges of a marketplace are the buyers' side's (`MKT_ENGINE_BRIDGES`); a sellers' number would be the supply's.
  const addForRow = (row: { motion: EngineMotion; metric: MetricId | DerivedId }) =>
    row.motion === "mkt" ? addFor("mkt", row.metric.startsWith("mkt.sell.") ? "supply" : "demand") : addFor(row.motion);
  // 2 — declared tracked at the Tour (20 points), and nobody could pull it.
  for (const row of derived.mirror?.rows ?? []) {
    if (row.declared === "tracked" && row.found === "unknown") addForRow(row)("blind-spot", [row.metric]);
  }
  // 4 — the positive one: declared unknown at the Tour, and measured here.
  for (const row of derived.mirror?.rows ?? []) {
    if (row.declared === "unknown" && row.found === "tracked") addForRow(row)("hidden-knowledge", [row.metric]);
  }

  // Stable: by rank, then by kind; within a kind, the order above (motions in canonical order, then metrics).
  return out
    .map((f, i) => ({ f, i }))
    .sort((a, b) => a.f.rank - b.f.rank || KIND_ORDER.indexOf(a.f.kind) - KIND_ORDER.indexOf(b.f.kind) || a.i - b.i)
    .map(({ f }) => f);
}

type Add = (kind: Finding["kind"], metrics: Finding["metrics"], values?: Record<string, string>, count?: Interval) => void;

/** What a diagnosis named, with its value and the comparator that named it — the same in both motions. */
function namedFindings(
  state: EngineState,
  diagnosis: AnyDiagnosis,
  ctx: EngineCalcContext,
  words: UnitWords,
  add: Add,
  noDecimals: (id: MetricId) => boolean,
): void {
  if (diagnosis.state !== "clear" && diagnosis.state !== "shared") return;
  const positions = diagnosis.positions as Partial<Record<CandidateId, { position: Position; comparator?: Comparator }>>;
  for (const id of diagnosis.named as CandidateId[]) {
    const comparator = positions[id]?.comparator;
    const known = knownIn(state, id, ctx);
    if (!comparator || known.kind !== "known") continue;
    add("below-comparator", [id], {
      value: formatInterval(known.value, shapeOf(id).unit, ctx, words, { noDecimals: noDecimals(id) }),
      comparator: formatComparator(comparator, id, state, ctx, words),
    });
  }
}

/** Two numbers that disagree, each with its own figure. */
function conflictFindings(state: EngineState, shapes: readonly MetricShape[], ctx: EngineCalcContext, words: UnitWords, add: Add): void {
  const snapshot = currentSnapshot(state);
  for (const shape of shapes) {
    const entry = entryOf(snapshot, shape.id);
    if (entry?.status !== "conflicting" || !entry.conflict) continue;
    add("conflict", [shape.id], {
      a: formatReading(entry.conflict.a.value, shape.id, state, ctx, words),
      b: formatReading(entry.conflict.b.value, shape.id, state, ctx, words),
    });
  }
}

/** The cost an LTV is set against, per type: the customer's CAC, the sales-assisted CAC, an app's cost per install, a marketplace's buyer CAC and its sellers' cost. */
type CostId = "acq.cac" | "slg.acq.cac" | "app.acq.cpi" | "mkt.buy.cac" | "mkt.sell.cac";
const LTV_OF: Record<CostId, DerivedId> = {
  "acq.cac": "rev.ltv",
  "slg.acq.cac": "slg.rev.ltv",
  "app.acq.cpi": "app.rev.install-ltv",
  "mkt.buy.cac": "mkt.rev.ltv",
  "mkt.sell.cac": "mkt.sell.ltv",
};

/**
 * The loss (§20.4, C48), on today's LTV and CAC of one motion — never summed
 * across motions. Arithmetic on the team's own numbers: no reference enters
 * it, so it names no stage. The CAC prints as typed (to the unit, or its
 * range), the LTV and the gap as the estimates they are (« ~1 500 € »). An
 * app's pair is its install's 36-month value and its cost per install
 * (§21.5.5, D10). A marketplace's paid seller is set against what a paid
 * seller costs, which is no number the person typed: `cacValue` stands in for
 * the read of `cacId` (§22.5.8), and `cacId` still names it in the finding.
 */
function lossFinding(state: EngineState, ltv: DerivedValue, cacId: CostId, ctx: EngineCalcContext, words: UnitWords, add: Add, cacValue?: Interval): void {
  const cacKnown = cacValue ? ({ kind: "known", value: cacValue } as const) : knownIn(state, cacId, ctx);
  if (ltv.kind !== "known" || cacKnown.kind !== "known") return;
  const loss = lossCheck(ltv.value, cacKnown.value);
  if (!loss || loss.verdict === "none") return;
  const currency = state.setup.currency;
  const cac = cacKnown.value;
  const shortfall = sub(cac, ltv.value);
  add(loss.verdict === "loss" ? "unit-econ-loss" : "unit-econ-loss-maybe", [LTV_OF[cacId], cacId], {
    cac: cac.lo === cac.hi ? formatInterval(cac, "money", ctx, words, { currency }) : formatApproxMoneyInterval(cac, currency, ctx, words),
    ltv: formatApproxMoneyInterval(ltv.value, currency, ctx, words),
    gap: formatApproxMoneyInterval({ lo: Math.max(0, shortfall.lo), hi: Math.max(0, shortfall.hi) }, currency, ctx, words),
  });
}

/** The payback can't be computed, and at least one of its inputs was looked for and not found. */
function paybackFinding(
  payback: DerivedValue,
  id: "rev.cac-payback" | "slg.rev.cac-payback" | "app.rev.install-payback" | "mkt.rev.cac-payback" | "mkt.sell.cac-payback",
  add: Add,
  missing: (id: MetricId) => boolean,
): void {
  if (payback.kind === "uncomputable" && payback.missing.some(missing)) add("unit-econ-uncomputable", [id, ...payback.missing]);
}

function selfServeFindings(
  state: EngineState,
  m: Extract<MotionDerived, { motion: "plg" }>,
  derived: Omit<EngineDerived, "findings">,
  ctx: EngineCalcContext,
  words: UnitWords,
  add: Add,
  missing: (id: MetricId) => boolean,
): void {
  const snapshot = currentSnapshot(state);
  const eventMissing = missing("act.event");
  // An app is read on the numbers its setup shows (§21.5.5): its own list, and its cost per install in place of the CAC.
  const app = isApp(state.setup);
  const shapes = app ? shapesOf(state.setup).filter((s) => s.scope === "plg" || s.scope === "app") : METRIC_SHAPES;

  // 1 — a ★ of the peloton that nobody could pull. The activation column breaks too when its EVENT is
  // missing: nobody can count activations of an action nobody has named, and it is said once (§5.3).
  for (const column of m.peloton.columns) {
    if (column.perHundred !== null) continue;
    if (column.metric === "act.rate" && eventMissing) add("chain-break", ["act.event", "act.rate"]);
    else if (missing(column.metric)) add("chain-break", [column.metric]);
  }

  // 2 — no shared definition. Not raised on the rate when its event is already the finding.
  for (const shape of shapes) {
    if (shape.id === "act.rate" && eventMissing) continue;
    if (entryOf(snapshot, shape.id)?.missing?.cause === "no-definition" && missing(shape.id)) add("no-definition", [shape.id]);
  }

  // 2 — the stages the diagnosis named.
  namedFindings(state, m.diagnosis, ctx, words, add, () => false);

  // 3
  conflictFindings(state, shapes, ctx, words, add);
  paybackFinding(m.unit.payback, app ? "app.rev.install-payback" : "rev.cac-payback", add, missing);
  lossFinding(state, m.unit.ltv, app ? "app.acq.cpi" : "acq.cac", ctx, words, add);

  // 3 — the chain and the billing don't describe the same population.
  const gap = derived.sanity.find((c) => c.id === "reconcile-gap");
  if (gap) add("reconcile-gap", gap.metrics, gap.values, gap.count);

  // 4 — each sign-up weighs more than a point.
  if (m.peloton.smallCohort) add("small-cohort", []);
}

/** §18.5.8: the same kinds and ranks, on the relays and the sales-assisted catalogue. */
function salesAssistedFindings(
  state: EngineState,
  m: Extract<MotionDerived, { motion: "slg" }>,
  ctx: EngineCalcContext,
  words: UnitWords,
  add: Add,
  missing: (id: MetricId) => boolean,
): void {
  const snapshot = currentSnapshot(state);
  const liveEventMissing = missing("slg.act.live-event");

  // 1 — a relay nobody could pull. Go-live with no definition of « live » is one finding, on the definition.
  for (const column of m.relays.columns) {
    if (column.perHundred !== null) continue;
    if (column.metric === "slg.act.go-live" && liveEventMissing) add("chain-break", ["slg.act.live-event", "slg.act.go-live"]);
    else if (missing(column.metric)) add("chain-break", [column.metric]);
  }

  // 2 — no shared definition. Not raised on go-live when its definition is already the finding.
  for (const shape of SLG_METRIC_SHAPES) {
    if (shape.id === "slg.act.go-live" && liveEventMissing) continue;
    if (entryOf(snapshot, shape.id)?.missing?.cause === "no-definition" && missing(shape.id)) add("no-definition", [shape.id]);
  }

  namedFindings(state, m.diagnosis, ctx, words, add, (id) => slgNoDecimals(snapshot, id));
  conflictFindings(state, SLG_METRIC_SHAPES, ctx, words, add);
  paybackFinding(m.unit.payback, "slg.rev.cac-payback", add, missing);
  lossFinding(state, m.unit.ltv, "slg.acq.cac", ctx, words, add);

  // 4 — the counted ★ on the smallest base: one more or less moves it by p points (§18.5.1).
  const sample = smallestSample(snapshot);
  if (sample) {
    const p = roundDisplay(sample.points);
    add("small-sample", [sample.metric], { d: formatNumber(sample.denominator, ctx.locale), p: formatInterval(point(sample.points), "ratio", ctx, words) }, point(p));
  }
}

/**
 * §22.5.8. The marketplace's findings, the copy of the self-serve ones on its two sides: each finding says the side of
 * its number (C70), the `match` ones (the fill rate, the take rate, the commissions' margin) the demand's. The two sides
 * are read one after the other, each on its own diagnosis and its own economics — never one against the other (D2).
 */
function marketplaceFindings(
  state: EngineState,
  m: Extract<MotionDerived, { motion: "mkt" }>,
  derived: Omit<EngineDerived, "findings">,
  ctx: EngineCalcContext,
  words: UnitWords,
  addFor: (side: MktSide) => Add,
  missing: (id: MetricId) => boolean,
): void {
  const snapshot = currentSnapshot(state);
  const demand = addFor("demand");
  const supply = addFor("supply");
  const { sellerSubscriptions } = mktSetup(state.setup);
  const shapes = shapesOf(state.setup);
  const sellers = (shape: MetricShape) => shape.side === "sell";

  // 1 — a column of a funnel that nobody could pull.
  for (const column of m.funnel.demand.columns) {
    if (column.perHundred === null && missing(column.metric)) demand("chain-break", [column.metric]);
  }
  for (const column of m.funnel.supply.columns) {
    if (column.perHundred === null && missing(column.metric)) supply("chain-break", [column.metric]);
  }

  // 2 — no shared definition.
  for (const shape of shapes) {
    if (entryOf(snapshot, shape.id)?.missing?.cause === "no-definition" && missing(shape.id)) (sellers(shape) ? supply : demand)("no-definition", [shape.id]);
  }

  // 2 — the stages each side's diagnosis named.
  namedFindings(state, m.sides.demand.diagnosis, ctx, words, demand, () => false);
  namedFindings(state, m.sides.supply.diagnosis, ctx, words, supply, () => false);

  // 3
  conflictFindings(state, shapes.filter((s) => !sellers(s)), ctx, words, demand);
  conflictFindings(state, shapes.filter(sellers), ctx, words, supply);
  paybackFinding(m.sides.demand.unit.payback, "mkt.rev.cac-payback", demand, missing);
  lossFinding(state, m.sides.demand.unit.ltv, "mkt.buy.cac", ctx, words, demand);
  if (sellerSubscriptions) {
    paybackFinding(m.sides.supply.unit.payback, "mkt.sell.cac-payback", supply, missing);
    // A paid seller is set against what a paid seller costs, not the cost of an active seller the person typed.
    const paidCost = mktPaidSellerCac(state, ctx);
    if (paidCost) lossFinding(state, m.sides.supply.unit.ltv, "mkt.sell.cac", ctx, words, supply, paidCost);
  }

  // 3 — the chain and the buyer CAC's count don't describe the same population (the demand's own check).
  const gap = derived.sanity.find((c) => c.id === "reconcile-gap" && c.motion === "mkt");
  if (gap) demand("reconcile-gap", gap.metrics, gap.values, gap.count);

  // 4 — each sign-up weighs more than a point, on a side's cohort.
  if (m.funnel.demand.smallCohort) demand("small-cohort", []);
  if (m.funnel.supply.smallCohort) supply("small-cohort", []);
}
